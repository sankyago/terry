export function createHardTickets(scenes: TicketTemplate[]): RankedTicketTemplate[] {
  const byId = new Map(scenes.map((scene) => [scene.id, scene]));
  return CASES.map(([sceneId, id, title, question, correct, other, another, explanation, rule, patch, companions = []], i) => {
    const scene = byId.get(sceneId);
    if (!scene) throw new Error(`Немає сцени для складного білета: ${sceneId}`);
    const extra = companions.map((id) => {
      const companion = byId.get(id);
      if (!companion) throw new Error(`Немає додаткової сцени: ${id}`);
      return companion;
    });
    const correctIndex = i % 3;
    const options = [other, another];
    options.splice(correctIndex, 0, correct);
    return {
      ...scene,
      actors: [
        ...scene.actors,
        ...extra.flatMap((t) => t.actors.map((a) => ({ ...a, id: `${t.id}/${a.id}` }))),
      ],
      signs: [...(scene.signs ?? []), ...extra.flatMap((t) => t.signs ?? [])],
      crosswalks: [...(scene.crosswalks ?? []), ...extra.flatMap((t) => t.crosswalks ?? [])],
      bikePaths: [...(scene.bikePaths ?? []), ...extra.flatMap((t) => t.bikePaths ?? [])],
      ...patch,
      id: `hard-${id}`,
      difficulty: 'hard',
      title,
      question,
      options: ask(options, correctIndex),
      explanation,
      rule: `ПДР, ${rule}`,
    };
  });
}
